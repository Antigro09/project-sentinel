"""X4: replace the label vocabulary with a DSL, and search beyond enumeration.

The staged gate asked three things of this experiment:

  1. the current 5,760 rule sets must be EXPRESSIBLE in the DSL, so the
     existing benchmark stays a valid regression test;
  2. search must survive a space too big to enumerate (exhaustive search
     stops fitting the budget somewhere past ~17,000 hypotheses);
  3. nothing upstream may know domain labels -- the whole point of Level 4.

The DSL is a product grammar over transition-rule productions; a program
compiles to `Mechanics`, so the EXACT reference model executes it and
correctness is inherited, not re-proved. The collection ORDER is part of a
program (a frame never reveals which target comes first).

MEASURED RESULTS:

  A. REGRESSION: 5,760/5,760 label-encoded rule sets compile byte-identical.
     The old benchmark remains valid.

  B. QUOTIENT AT SCALE: signatures ~ K^0.43 holds at 61,440 (10,000 sampled
     programs -> 377 behaviours). The quotient law is not an artefact of
     the small space.

  C. EVIDENCE QUOTIENT: bulk refutation of ALL 61,440 programs x orders
     against one episode: 600k transitions in 2.4s -> 24 survivors, truth
     among them. A space 3.6x past exhaustive reach is searched in seconds.

  D. RECOVERY: refute-then-select recovers extended truths up to the
     EVIDENCE's resolution -- 6/15 bisimilar under a 40-step probe, and in
     every miss checked the TRUTH SURVIVED refutation but lost selection to
     a simpler program that agrees on all observed frames (charge=4 vs
     charge=16 when the episode never ticked the difference). Coordinate
     ascent was tried first and failed completely (0/15): the fitness
     landscape has no single-axis gradient -- every wrong program scores
     fitness 0.000 until most axes are simultaneously right. Refutation is
     exact where fitness is coarse.

TWO BUGS FOUND ON THE WAY, both worth recording:

  - SpecCache originally keyed on the program alone, silently giving every
    collection order the raster layout -- which refuted the truth. Order
    is part of the hypothesis; caches must key on it.
  - The first recovery test judged extended truths against episodes
    generated by the DONOR's mechanics. The truth scored fitness 0.026.
    Evidence must come FROM the hypothesis under test.

THE HONEST BOUNDARY: misses are not search failures but evidence-resolution
limits -- the random-walk explorer visits ~5 distinct states on these
boards, so counterfactual differences (the charge period) are never
excited. This re-confirms X8/X9 from the Level 4 side: the identifiability
lever is the exploration policy (planned_information_gain_history), which
is X18. Level 4's architecture stands: programs, not labels; behaviours,
not enumerations.
"""

